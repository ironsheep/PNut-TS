<#
.SYNOPSIS
    Shared engine for all per-suite rebuild-gold.ps1 scripts.

.DESCRIPTION
    Each per-suite rebuild-gold.ps1 is a thin wrapper, generated by
    scripts/gold/gen-rebuild-scripts.js, that dot-sources this file and calls
    Invoke-RebuildGold with its suite-specific data.

    Behaviors handled here so per-suite scripts stay tiny:
      - PNut binary path resolution (auto-find at standard install location)
      - Cleanup of the outputs and GOLDs of the fixtures being regenerated, and
        of nothing else
      - File-loop with per-file/per-pattern flag overrides
      - Each compile runs under a timeout; one that overruns has its whole
        process tree killed and is recorded TIMED-OUT
      - Expected to compile: outputs renamed to .GOLD (lst, obj, bin, flash, ...)
      - Expected to fail (-ExpectFail): Error.txt renamed to <base>.errout.GOLD
      - Skip list: never compiled, GOLDs left in place (goldSource pnut-ts
        fixtures and hand skips)
      - One outcome per fixture, returned in $stats.results; rebuild-gold-all.ps1
        writes them to TEST\gold-run-summary.txt

    Outcomes:
      CAPTURED                        the GOLDs this fixture should have were written
      COMPILED-BUT-EXPECTED-TO-FAIL   PNut compiled an expected-fail fixture; no GOLD
      FAILED-BUT-EXPECTED-TO-COMPILE  PNut reported an error for an expected-compile fixture
      NO-ERROR-TXT                    no Error.txt and no output after the compile
      TIMED-OUT                       the compile overran and was killed
      RENAME-FAILED                   an output or Error.txt stayed locked
      NO-OUTPUT                       Error.txt said okay but none of -Produces appeared
      SKIPPED                         in -Skip; not compiled

    Two run options come from the environment, set by rebuild-gold-all.ps1, so
    the per-suite wrappers do not have to pass them on:
      PNUTTS_GOLD_TIMEOUT_SECONDS  per-compile timeout in seconds (default 60)
      PNUTTS_GOLD_ONLY             file names separated by ';': compile only these

.NOTES
    Compatible with Windows PowerShell 5.1 (default on Windows). No PS7-only
    cmdlets, no module dependencies, no JSON parsing.
#>

function Add-GoldResult {
    # Record one fixture's outcome: print it, keep it for the summary, count it.
    param(
        [hashtable]$Stats,
        [string]$File,
        [string]$Flag,
        [string]$Expect,
        [string]$Outcome,
        [string]$Detail = ""
    )
    $line = "  $File ($Flag, expect $Expect) -> $Outcome"
    if ($Detail -ne "") { $line += ": $Detail" }
    Write-Output $line
    [void]$Stats.results.Add([PSCustomObject]@{
        File    = $File
        Flag    = $Flag
        Expect  = $Expect
        Outcome = $Outcome
        Detail  = $Detail
    })
    if ($Outcome -eq "CAPTURED") {
        $Stats.ok++
    } elseif ($Outcome -eq "SKIPPED") {
        $Stats.skipped++
    } else {
        $Stats.failed++
    }
}

function Rename-GoldWithRetry {
    # Rename $Source to $NewName, retrying while the file is locked: Windows PNut
    # sometimes holds output handles briefly, and Dropbox/OneDrive/AV scanners
    # can grab fresh files for a moment. Returns "" on success, else the reason.
    param(
        [string]$Source,
        [string]$NewName
    )
    $attempts = 0
    $maxAttempts = 6  # total wait on failure: 200+400+800+1600+3200 = 6.2s
    $delay = 200
    while ($attempts -lt $maxAttempts) {
        try {
            Rename-Item -LiteralPath $Source -NewName $NewName -Force -ErrorAction Stop
            return ""
        } catch [System.IO.IOException] {
            $attempts++
            if ($attempts -ge $maxAttempts) {
                return $_.Exception.Message
            }
            Start-Sleep -Milliseconds $delay
            $delay *= 2
        } catch {
            return $_.Exception.Message
        }
    }
    return "not renamed"
}

function Invoke-PNutCompile {
    # Compile one file in the current directory through cmd /c, waiting at most
    # $TimeoutSeconds. Returns "done", "timed-out" (the whole process tree was
    # killed: a .bat wrapper killed alone leaves PNut running), or
    # "not-started: <reason>".
    param(
        [string]$PNutBinary,
        [string]$Flag,
        [string]$FileName,
        [int]$TimeoutSeconds
    )
    # /s: cmd removes exactly the outer pair of quotes, so a binary path with
    # spaces stays quoted. /d: no AutoRun commands. The flag and file name reach
    # the binary as the same two plain arguments a direct call passes.
    $cmdArgs = '/d /s /c ""' + $PNutBinary + '" ' + $Flag + ' ' + $FileName + '"'
    # The compiler's console output is discarded, as a direct call's "> $null 2>&1"
    # would. Fresh names per compile: a killed process cannot hold the next one's.
    $tag = [guid]::NewGuid().ToString("N")
    $outLog = Join-Path $env:TEMP "rebuild-gold-$tag.out"
    $errLog = Join-Path $env:TEMP "rebuild-gold-$tag.err"
    try {
        $proc = Start-Process -FilePath "cmd.exe" -ArgumentList $cmdArgs `
            -WorkingDirectory $PWD.ProviderPath -NoNewWindow -PassThru `
            -RedirectStandardOutput $outLog -RedirectStandardError $errLog `
            -ErrorAction Stop
    } catch {
        return "not-started: $($_.Exception.Message)"
    }
    $state = "done"
    if (-not $proc.WaitForExit($TimeoutSeconds * 1000)) {
        & taskkill.exe /T /F /PID $proc.Id > $null 2>&1
        $proc.WaitForExit(10000) | Out-Null
        $state = "timed-out"
    }
    Remove-Item -LiteralPath @($outLog, $errLog) -Force -ErrorAction SilentlyContinue
    return $state
}

function Invoke-RebuildGold {
    param(
        # Compiler selection
        [int]$PNutVersion = 55,
        [string]$PNutInstallRoot = "C:\Program Files (x86)\Parallax Inc",
        [string]$PNutBinary = "",

        # Per-suite rules
        [string]$DefaultFlag = "-c",
        [string[]]$Produces = @("lst", "obj", "bin"),
        [hashtable]$PerFileFlag = @{},
        [hashtable]$PerFilePatternFlag = @{},
        [string[]]$Skip = @(),
        [string[]]$ExpectFail = @(),

        # Run options; 0 / empty take the environment (see the header), then the default
        [int]$CompileTimeoutSeconds = 0,
        [string[]]$Only = @()
    )

    # ---- Resolve PNut binary -----------------------------------------------
    # We need the HEADLESS PNut: PNut_shell.bat (no version suffix) inside the
    # versioned install dir PNut_v${N}\. NOT the GUI editor (PNut_v${N}.exe),
    # which is interactive and ignores -c/-cd. Version selection happens by
    # which install directory we invoke PNut_shell.bat from.

    if (-not $PNutBinary) {
        $shellPath = Join-Path $PNutInstallRoot "PNut_v${PNutVersion}\PNut_shell.bat"
        if (Test-Path $shellPath) {
            $PNutBinary = $shellPath
        } elseif (Get-Command "PNut_shell.bat" -ErrorAction SilentlyContinue) {
                        $PNutBinary = "PNut_shell.bat"
        } else {
            Write-Error @"
PNut_shell.bat (v${PNutVersion}) not found.
  Looked at: $shellPath
  Also tried on PATH: PNut_shell.bat
NOTE: We need the headless variant (PNut_shell.bat inside the PNut_v${PNutVersion}\
      install dir), not the GUI editor (PNut_v${PNutVersion}.exe). The GUI does
      not produce .lst/.obj/.bin output from the command line.
"@
            return
        }
    }

    if ($PNutBinary -match "[\\/]" -and -not (Test-Path $PNutBinary)) {
        Write-Error "PNut binary not found at: $PNutBinary"
        return
    }

    # ---- Resolve run options -----------------------------------------------

    if ($CompileTimeoutSeconds -le 0) {
        $CompileTimeoutSeconds = 60
        if ($env:PNUTTS_GOLD_TIMEOUT_SECONDS) {
            $CompileTimeoutSeconds = [int]$env:PNUTTS_GOLD_TIMEOUT_SECONDS
        }
    }
    if ($Only.Count -eq 0 -and $env:PNUTTS_GOLD_ONLY) {
        $Only = @($env:PNUTTS_GOLD_ONLY -split ';' | Where-Object { $_ -ne "" })
    }

    Write-Output ""
    Write-Output "=== Suite: $($PWD.Path) ==="
    Write-Output "    Compiler:     $PNutBinary"
    Write-Output "    Default flag: $DefaultFlag"
    Write-Output "    Produces:     $($Produces -join ', ')"
    Write-Output "    Timeout:      $CompileTimeoutSeconds s per compile"
    if ($PerFileFlag.Count -gt 0) {
        Write-Output "    Per-file overrides: $($PerFileFlag.Count) file(s)"
    }
    if ($PerFilePatternFlag.Count -gt 0) {
        Write-Output "    Per-pattern overrides: $($PerFilePatternFlag.Count) pattern(s)"
    }
    if ($Skip.Count -gt 0) {
        Write-Output "    Skip:         $($Skip -join ', ')"
    }
    if ($ExpectFail.Count -gt 0) {
        Write-Output "    Expect fail:  $($ExpectFail.Count) file(s); Error.txt -> <base>.errout.GOLD"
    }
    if ($Only.Count -gt 0) {
        Write-Output "    Only:         $($Only -join ', ')"
    }

    # ---- Cleanup: only what the fixtures about to be compiled will remake ---
    # A skipped fixture keeps its GOLDs, and a file a FILE directive pulls in
    # (WUMMI's Type1.bin) is not an output, so neither is touched. The GOLDs
    # being remade go first, so a partial run leaves them visibly missing
    # rather than mixing old and new.

    $cleanupGlobs = @("*__pre.spin2", "*-pre.spin2", "Error.txt")
    Remove-Item -Force -ErrorAction SilentlyContinue $cleanupGlobs

    $files = @(Get-ChildItem -Filter *.spin2 | Sort-Object Name | Where-Object {
        $_.Name -notlike "*__pre.spin2" -and $_.Name -notlike "*-pre.spin2"
    })
    if ($Only.Count -gt 0) {
        $files = @($files | Where-Object { $Only -contains $_.Name })
    }

    foreach ($f in $files) {
        if ($Skip -contains $f.Name) { continue }
        $doomed = @()
        foreach ($ext in $Produces) {
            $doomed += "$($f.BaseName).$ext"
            $doomed += "$($f.BaseName).$ext.GOLD"
        }
        if ($ExpectFail -contains $f.Name) {
            $doomed += "$($f.BaseName).errout.GOLD"
        }
        Remove-Item -LiteralPath $doomed -Force -ErrorAction SilentlyContinue
    }

    # ---- Process each .spin2 -----------------------------------------------

    $stats = @{ ok = 0; failed = 0; skipped = 0; results = (New-Object System.Collections.ArrayList) }

    foreach ($f in $files) {
        $fileName = $f.Name
        $baseName = $f.BaseName
        $expect = "compile"
        if ($ExpectFail -contains $fileName) { $expect = "fail" }

        # Resolve flag for this file (exact-match first, then pattern)
        $flag = $DefaultFlag
        if ($PerFileFlag.ContainsKey($fileName)) {
            $flag = $PerFileFlag[$fileName]
        } else {
            foreach ($pattern in $PerFilePatternFlag.Keys) {
                if ($fileName -like $pattern) {
                    $flag = $PerFilePatternFlag[$pattern]
                    break
                }
            }
        }

        # Skip explicitly listed files
        if ($Skip -contains $fileName) {
            Add-GoldResult $stats $fileName $flag $expect "SKIPPED" "in -Skip; GOLDs left in place"
            continue
        }

        # Compile. Error.txt is removed first so a stale one from the previous
        # file is never read as this file's.
        Remove-Item -Force -ErrorAction SilentlyContinue "Error.txt"
        $state = Invoke-PNutCompile -PNutBinary $PNutBinary -Flag $flag -FileName $fileName -TimeoutSeconds $CompileTimeoutSeconds

        if ($state -eq "timed-out") {
            foreach ($ext in $Produces) {
                Remove-Item -LiteralPath "$baseName.$ext" -Force -ErrorAction SilentlyContinue
            }
            Add-GoldResult $stats $fileName $flag $expect "TIMED-OUT" "killed after $CompileTimeoutSeconds s with its process tree; no GOLD written"
            continue
        }
        if ($state -ne "done") {
            Add-GoldResult $stats $fileName $flag $expect "NO-ERROR-TXT" $state
            continue
        }

        # Brief sleep — Windows PNut sometimes holds output handles briefly,
        # and Dropbox/OneDrive/AV scanners can grab fresh files for a moment.
        # 300ms matches the long-standing legacy convention; retry covers the
        # case where the initial sleep wasn't enough.
        Start-Sleep -Milliseconds 300

        # Read Error.txt: "okay" or empty means the compile succeeded.
        $haveErrorTxt = Test-Path -LiteralPath "Error.txt"
        $errorMessage = ""
        if ($haveErrorTxt) {
            $content = Get-Content -LiteralPath "Error.txt" -Raw
            if ($null -eq $content) { $content = "" }
            $content = $content.Trim()
            if ($content -ne "okay") {
                $errorMessage = $content
            }
        }
        $errorOneLine = $errorMessage -replace '\s*\r?\n\s*', ' | '

        $producedExts = @()
        foreach ($ext in $Produces) {
            if (Test-Path -LiteralPath "$baseName.$ext") { $producedExts += $ext }
        }

        # ---- Expected to fail: Error.txt becomes <base>.errout.GOLD ---------
        if ($expect -eq "fail") {
            if ($errorMessage -ne "") {
                $why = Rename-GoldWithRetry -Source "Error.txt" -NewName "$baseName.errout.GOLD"
                if ($why -eq "") {
                    Add-GoldResult $stats $fileName $flag $expect "CAPTURED" ".errout.GOLD <- $errorOneLine"
                } else {
                    Add-GoldResult $stats $fileName $flag $expect "RENAME-FAILED" "Error.txt -> $baseName.errout.GOLD: $why"
                }
            } elseif (-not $haveErrorTxt -and $producedExts.Count -eq 0) {
                Add-GoldResult $stats $fileName $flag $expect "NO-ERROR-TXT" "no Error.txt and none of: $($Produces -join ',')"
            } else {
                foreach ($ext in $producedExts) {
                    Remove-Item -LiteralPath "$baseName.$ext" -Force -ErrorAction SilentlyContinue
                }
                Add-GoldResult $stats $fileName $flag $expect "COMPILED-BUT-EXPECTED-TO-FAIL" "PNut compiled it (produced: $($producedExts -join ',')); no GOLD written"
            }
            continue
        }

        # ---- Expected to compile: outputs become .GOLD ---------------------
        if ($errorMessage -ne "") {
            Add-GoldResult $stats $fileName $flag $expect "FAILED-BUT-EXPECTED-TO-COMPILE" $errorOneLine
            continue
        }
        if ($producedExts.Count -eq 0) {
            if (-not $haveErrorTxt) {
                Add-GoldResult $stats $fileName $flag $expect "NO-ERROR-TXT" "no Error.txt and none of: $($Produces -join ',')"
            } else {
                Add-GoldResult $stats $fileName $flag $expect "NO-OUTPUT" "compiled but produced none of: $($Produces -join ',')"
            }
            continue
        }

        # Rename produced outputs to .GOLD (with retry for file-lock races).
        $renamedExts = @()
        $renameErrors = @()
        foreach ($ext in $producedExts) {
            $why = Rename-GoldWithRetry -Source "$baseName.$ext" -NewName "$baseName.$ext.GOLD"
            if ($why -eq "") {
                $renamedExts += $ext
            } else {
                $renameErrors += "${ext}: $why"
            }
        }
        Remove-Item -Force -ErrorAction SilentlyContinue "Error.txt"

        if ($renameErrors.Count -gt 0) {
            Add-GoldResult $stats $fileName $flag $expect "RENAME-FAILED" "renamed [$($renamedExts -join ',')], FAILED [$($renameErrors -join '; ')]"
        } else {
            Add-GoldResult $stats $fileName $flag $expect "CAPTURED" ".$($renamedExts -join '.GOLD .').GOLD"
        }
    }

    Write-Output "    Summary: ok=$($stats.ok) failed=$($stats.failed) skipped=$($stats.skipped)"
    return $stats
}
